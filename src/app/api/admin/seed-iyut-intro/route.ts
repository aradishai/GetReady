export async function POST(req: NextRequest) {
  try {
    const session = await auth()
    if (!session?.user?.isAdmin) {
      return NextResponse.json({ error: "אין הרשאה" }, { status: 403 })
    }

    const reset = new URL(req.url).searchParams.get("reset") === "true"

    if (reset) {
      await prisma.question.deleteMany({
        where: { courseId: "course-iyut", topic: TOPIC },
      })
    }

    let created = 0
    for (const q of QUESTIONS) {
      const existing = await prisma.question.findFirst({
        where: { courseId: "course-iyut", question: q.question },
      })
      if (!existing) {
        await prisma.question.create({
          data: {
            courseId: "course-iyut",
            topic: TOPIC,
            question: q.question,
            answerA: q.answerA,
            answerB: q.answerB,
            answerC: q.answerC,
            answerD: q.answerD,
            correctAnswer: "B",
            explanation: q.explanation,
            difficulty: "Hard",
            sourceType: "Manual",
            position: 7,
          },
        })
        created++
      }
    }

    return NextResponse.json({ success: true, created, total: QUESTIONS.length })
  } catch (e) {
    console.error("seed-iyut-intro error:", e)
    return NextResponse.json({ error: "שגיאה" }, { status: 500 })
  }
}
