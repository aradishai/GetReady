async function main() {
  const existing = await prisma.question.count({
    where: { courseId: "course-assessment", position: 72 },
  })

  if (existing > 0) {
    console.log("Assessment interview-72 questions already seeded, skipping")
    return
  }

  let added = 0
  for (const q of QUESTIONS) {
    await prisma.question.create({
      data: { courseId: "course-assessment", ...q, position: 72, sourceType: "Uploaded" },
    })
    added++
  }

  console.log(`Added ${added} new questions to course-assessment (ראיון עבודה, position 72)`)
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect())
