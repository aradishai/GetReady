async function main() {
  const existing = await prisma.question.findFirst({
    where: { courseId: "course-iyut", question: QUESTIONS[0].question },
  })

  if (existing) {
    console.log(`${TOPIC} already seeded, skipping`)
    return
  }

  let added = 0
  for (const q of QUESTIONS) {
    await prisma.question.create({
      data: { courseId: "course-iyut", topic: TOPIC, position: 13, sourceType: "Manual", correctAnswer: "B", difficulty: "Hard", ...q },
    })
    added++
  }

  console.log(`נוספו ${added} שאלות לקורס אישיות (${TOPIC})`)
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect())
