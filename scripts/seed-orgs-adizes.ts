async function main() {
  let added = 0
  for (const q of QUESTIONS) {
    const exists = await prisma.question.findFirst({
      where: { courseId: "course-orgs", topic: TOPIC, question: q.question },
    })
    if (!exists) {
      await prisma.question.create({
        data: { courseId: "course-orgs", topic: TOPIC, position: 2, sourceType: "Manual", ...q },
      })
      added++
    }
  }
  if (added > 0) console.log(`נוספו ${added} שאלות לקורס ארגונים (${TOPIC})`)
  else console.log(`${TOPIC} כבר קיים, דילוג`)
}

