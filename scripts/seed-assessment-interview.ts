async function main() {
  const existing = await prisma.question.findFirst({
    where: {
      courseId: "course-assessment",
      question: QUESTIONS[0].question,
    },
  })

  if (existing) {
    console.log("Assessment interview questions already seeded, skipping")
    return
  }

  let added = 0
  for (const q of QUESTIONS) {
    await prisma.question.create({
      data: { courseId: "course-assessment", ...q, position: 70, sourceType: "Uploaded" },
    })
    added++
  }

  console.log(`Added ${added} new questions to course-assessment (ראיון עבודה)`)
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect())
