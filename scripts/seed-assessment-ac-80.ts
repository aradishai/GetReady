async function main() {
  const existing = await prisma.question.count({
    where: { courseId: "course-assessment", position: 80 },
  })

  if (existing > 0) {
    console.log("Assessment ac-80 questions already seeded, skipping")
    return
  }

  let added = 0
  for (const q of QUESTIONS) {
    await prisma.question.create({
      data: { courseId: "course-assessment", ...q, position: 80, sourceType: "Uploaded" },
    })
    added++
  }

  console.log(`Added ${added} new questions to course-assessment (מרכז הערכה, position 80)`)
}

