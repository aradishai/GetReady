async function main() {
  const existing = await prisma.question.count({
    where: { courseId: "course-assessment", position: 71 },
  })

  if (existing > 0) {
    console.log("Assessment interview-71 questions already seeded, skipping")
    return
  }

  let added = 0
  for (const q of QUESTIONS) {
    await prisma.question.create({
      data: { courseId: "course-assessment", ...q, position: 71, sourceType: "Uploaded" },
    })
    added++
  }

  console.log(`Added ${added} new questions to course-assessment (ראיון עבודה, position 71)`)
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect())
