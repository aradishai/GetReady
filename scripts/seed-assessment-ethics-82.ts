async function main() {
  const existing = await prisma.question.count({
    where: { courseId: "course-assessment", position: 82 },
  })

  if (existing > 0) {
    console.log("Assessment ethics-82 questions already seeded, skipping")
    return
  }

  let added = 0
  for (const q of QUESTIONS) {
    await prisma.question.create({
      data: { courseId: "course-assessment", ...q, position: 82, sourceType: "Uploaded" },
    })
    added++
  }

  console.log(`Added ${added} new questions to course-assessment (הוגנות ואתיקה, position 82)`)
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect())
