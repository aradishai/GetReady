async function main() {
  let added = 0
  for (const q of QUESTIONS) {
    const exists = await prisma.question.findFirst({
      where: { courseId: "course-psychodiag", topic: TOPIC, question: q.question },
    })
    if (!exists) {
      await prisma.question.create({
        data: { courseId: "course-psychodiag", topic: TOPIC, position: 1, sourceType: "Manual", isActive: true, ...q },
      })
      added++
    }
  }
  if (added > 0) console.log(`נוספו ${added} שאלות לקורס פסיכודיאגנוסטיקה (${TOPIC})`)
  else console.log(`${TOPIC} כבר קיים, דילוג`)
}

