async function main() {
  const existing = await prisma.question.count({
    where: { courseId: "course-iyut", topic: TOPIC },
  })

  if (existing > 0) {
    console.log(`כבר קיימות ${existing} שאלות ב-${TOPIC}, מדלג`)
    return
  }

  let added = 0
  for (const q of QUESTIONS) {
    await prisma.question.create({
      data: { courseId: "course-iyut", topic: TOPIC, position: 0, sourceType: "Manual", ...q },
    })
    added++
  }

  console.log(`נוספו ${added} שאלות לקורס אישיות (${TOPIC})`)
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect())
